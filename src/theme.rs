/// `$XDG_CONFIG_HOME/detune/theme`, falling back to `$HOME/.config/detune/theme`.
/// Returns `None` if no usable home is available.
fn config_path() -> Option<PathBuf> {
    let base = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")))?;
    Some(base.join("detune").join("theme"))
}

pub fn save_theme_idx(idx: usize) {
    let Some(theme) = THEMES.get(idx) else { return };
    let Some(path) = config_path() else { return };
    if let Some(parent) = path.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    let _ = std::fs::write(&path, theme.name);
}

pub fn load_theme_idx() -> usize {
    let Some(path) = config_path() else { return 0 };
    let Ok(contents) = std::fs::read_to_string(&path) else { return 0 };
    let name = contents.trim();
    THEMES
        .iter()
        .position(|t| t.name.eq_ignore_ascii_case(name))
        .unwrap_or(0)
}
